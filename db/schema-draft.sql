-- =====================================================================
-- Pulaski — core database schema, draft 0.1                2026-10-12
-- Target: PostgreSQL 18. Clean-room; ISA-95 / ISA-88 / PackML / ISO 22400.
--
-- Scope of this draft
--   1. Equipment model: work centers, work cells/units, machines, storage
--   2. Scheduling: manufacturing order > work order > job > run   [D-003]
--   3. Execution: consumption, production, labor, SPC
--   4. Utilization and OEE
--   5. User control (OIDC identity, scoped roles, terminals)
--
-- Conventions
--   * Every id is a native uuid holding a UUIDv7 generated by the app
--     (Guid.CreateVersion7()); uuidv7() is only a backstop.       [D-006]
--   * Schemas:  core = relational master data and current state
--               ts   = time-partitioned history and rollups       [D-010]
--               evt  = append-only event log / outbox    [D-004/007/008]
--               sec  = identity and access
--   * Status/kind columns are text + CHECK, not PG enums, so values can
--     be added or retired without ALTER TYPE.
--   * No foreign key ever targets a partitioned table, so partitions can
--     be detached and dropped freely. Rows that point into history carry
--     (id, occurred_at) without an FK.
--   * Optimistic concurrency uses xmin, read with SELECT ... FOR UPDATE and checked by the app; there are
--     no row_version columns.
--   * Business keys (order numbers, lot numbers, equipment codes) are
--     separate unique columns, never the PK.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- uuid equality inside EXCLUDE constraints

CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS ts;
CREATE SCHEMA IF NOT EXISTS evt;
CREATE SCHEMA IF NOT EXISTS sec;

CREATE DOMAIN core.qty AS numeric(18,6);

-- =====================================================================
-- 1. REFERENCE DATA
-- =====================================================================

-- Units of measure (D-026). A unit with a factor converts to every other unit of its
-- dimension for any material (kg, lb, m, ft). A packaging unit (box, bag, pallet) has no
-- factor: it converts only through a material's own conversion.
CREATE TABLE core.uom (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    code            text NOT NULL UNIQUE,              -- 'kg', 'lb', 'm', 'ft', 'ea', 'box'
    name            text NOT NULL,
    dimension       text NOT NULL CHECK (dimension IN ('mass','length','count','volume','area','time','other')),
    to_base_factor  numeric(24,12) CHECK (to_base_factor > 0),  -- multiply to reach the dimension's base unit; null: packaging
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uom_packaging_ck CHECK (to_base_factor IS NOT NULL OR dimension = 'other')
);

-- PackML StateCurrent numbering (ISA-TR88.00.02). Code is the standard number,
-- not a surrogate id. 0 = Undefined is NOT a PackML state: Pulaski uses it for
-- "no signal" (edge offline, tag bad quality) so lost time is never hidden.
CREATE TABLE core.packml_state (
    code        smallint PRIMARY KEY CHECK (code BETWEEN 0 AND 17),
    name        text NOT NULL UNIQUE,
    is_acting   boolean NOT NULL               -- transient "-ing" states
);

-- =====================================================================
-- 2. EQUIPMENT MODEL (ISA-95 Part 2 role-based hierarchy)
--    Work centers, work cells, machines and storage all live in one
--    self-referencing table; level + role says what each row is.
-- =====================================================================

CREATE TABLE core.equipment (
    id                      uuid PRIMARY KEY DEFAULT uuidv7(),
    parent_id               uuid REFERENCES core.equipment(id),
    site_id                 uuid REFERENCES core.equipment(id),     -- denormalized owning site (a site row points to itself)
    code                    text NOT NULL,                          -- business key, unique within site
    name                    text NOT NULL,
    description             text,
    level                   text NOT NULL,
    equipment_role          text NOT NULL,
    -- capability flags: what the rest of the model may do with this row
    tracks_state            boolean NOT NULL DEFAULT false,         -- has PackML state, downtime, OEE
    is_schedulable          boolean NOT NULL DEFAULT false,         -- a planning target: jobs can be planned to it (a line, or a department)
    can_run_job             boolean NOT NULL DEFAULT false,         -- executes jobs; a schedulable row without it is a group whose runners do (D-022)
    holds_inventory         boolean NOT NULL DEFAULT false,         -- lots can be located here
    commingles_lots         boolean NOT NULL DEFAULT false,         -- lots here mix into one balance per material, like a silo (D-031)
    flow_model              text NOT NULL DEFAULT 'mixed' CHECK (flow_model IN ('mixed','fifo')),   -- how a balance here flows, for genealogy (D-060)
    min_residence           interval CHECK (min_residence IS NULL OR min_residence >= interval '0'), -- the least time material stays before it can leave
    single_material         boolean NOT NULL DEFAULT false,         -- takes one material at a time (D-032)
    -- machine data (D-050): where its state comes from, and how short a stop is a micro-stop
    state_derivation        text NOT NULL DEFAULT 'own_tags' CHECK (state_derivation IN ('own_tags','series','parallel','constraint_machine')),
    constraint_equipment_id uuid REFERENCES core.equipment(id),
    micro_stop_threshold    interval NOT NULL DEFAULT interval '5 minutes',
    time_zone               text,                                   -- IANA zone, required on sites
    is_active               boolean NOT NULL DEFAULT true,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT equipment_level_role_ck CHECK ((level, equipment_role) IN (
        ('enterprise','enterprise'),
        ('site','site'),
        ('area','area'),
        ('work_center','production_line'),
        ('work_center','process_cell'),
        ('work_center','production_unit'),
        ('work_center','storage_zone'),
        ('work_unit','work_cell'),
        ('work_unit','unit'),
        ('work_unit','machine'),
        ('work_unit','storage_unit'),
        ('equipment_module','machine'),
        ('equipment_module','feed_point'),     -- hopper, feeder, unwind: where lots enter a line
        ('equipment_module','module'),
        ('control_module','module'))),
    CONSTRAINT equipment_site_ck CHECK (level = 'enterprise' OR site_id IS NOT NULL),
    CONSTRAINT equipment_tz_ck   CHECK (level <> 'site' OR time_zone IS NOT NULL),
    CONSTRAINT equipment_root_ck CHECK ((level = 'enterprise') = (parent_id IS NULL)),
    CONSTRAINT equipment_derivation_ck CHECK ((state_derivation = 'constraint_machine') = (constraint_equipment_id IS NOT NULL)),
    CONSTRAINT equipment_micro_stop_ck CHECK (micro_stop_threshold >= interval '0' AND micro_stop_threshold <= interval '1 hour'),
    CONSTRAINT equipment_commingles_ck CHECK (NOT commingles_lots OR holds_inventory),
    CONSTRAINT equipment_single_material_ck CHECK (NOT single_material OR holds_inventory),
    CONSTRAINT equipment_code_uq UNIQUE (site_id, code)
);
CREATE INDEX equipment_parent_ix ON core.equipment (parent_id);

-- Closure table: every ancestor/descendant pair, including self at depth 0.
-- Maintained by the app on insert/move. Drives scoped permissions and
-- "everything under this area" rollups without recursive CTEs.
CREATE TABLE core.equipment_closure (
    ancestor_id     uuid NOT NULL REFERENCES core.equipment(id) ON DELETE CASCADE,
    descendant_id   uuid NOT NULL REFERENCES core.equipment(id) ON DELETE CASCADE,
    depth           smallint NOT NULL CHECK (depth >= 0),
    PRIMARY KEY (ancestor_id, descendant_id)
);
CREATE INDEX equipment_closure_desc_ix ON core.equipment_closure (descendant_id, depth);

-- Material flow between equipment (silo -> feeder -> extruder -> puller -> saw).
-- The containment hierarchy says where things are; links say where material goes.
CREATE TABLE core.equipment_link (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    from_equipment_id   uuid NOT NULL REFERENCES core.equipment(id),
    to_equipment_id     uuid NOT NULL REFERENCES core.equipment(id),
    link_kind           text NOT NULL DEFAULT 'material_flow' CHECK (link_kind IN ('material_flow','rework_return')),
    is_active           boolean NOT NULL DEFAULT true,
    CONSTRAINT equipment_link_self_ck CHECK (from_equipment_id <> to_equipment_id),
    CONSTRAINT equipment_link_uq UNIQUE (from_equipment_id, to_equipment_id, link_kind)
);

-- Residence time across a link, optionally per material. 'speed_scaled' answers
-- the open genealogy question without forcing it: residence = ref_residence * ref_speed / actual_speed.
CREATE TABLE core.residence_time (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    equipment_link_id   uuid NOT NULL REFERENCES core.equipment_link(id) ON DELETE CASCADE,
    material_id         uuid,                                   -- FK added after core.material
    basis               text NOT NULL DEFAULT 'fixed' CHECK (basis IN ('fixed','speed_scaled')),
    ref_residence       interval NOT NULL,
    ref_speed           numeric(18,6),
    CONSTRAINT residence_speed_ck CHECK (basis = 'fixed' OR ref_speed > 0),
    CONSTRAINT residence_time_uq UNIQUE NULLS NOT DISTINCT (equipment_link_id, material_id)
);

-- Pulaski Edge nodes (D-050): a worker on plant hardware that runs connectors, buffers what they read and forwards it.
-- It signs in as a service user holding edge.ingest at the site. stream_id/last_sequence make forwarding idempotent:
-- a batch at or below last_sequence of the same stream was already applied.
CREATE TABLE core.edge_node (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    site_id             uuid NOT NULL REFERENCES core.equipment(id),
    code                text NOT NULL,                          -- upper case, fixed once created
    name                text NOT NULL,
    description         text,
    is_active           boolean NOT NULL DEFAULT true,
    stream_id           uuid,                                   -- the edge's buffer; a new one restarts the sequence
    last_sequence       bigint NOT NULL DEFAULT 0,
    last_seen_at        timestamptz,
    agent_version       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT edge_node_code_uq UNIQUE (site_id, code)
);

-- One data source an edge node reads, through one connector: an MQTT Sparkplug B broker today (D-050).
-- Secrets (broker passwords) stay in the edge's own configuration, never here.
CREATE TABLE core.edge_connection (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    edge_node_id        uuid NOT NULL REFERENCES core.edge_node(id),
    code                text NOT NULL,
    name                text NOT NULL,
    protocol            text NOT NULL CHECK (protocol IN ('sparkplug_b')),
    settings            jsonb NOT NULL DEFAULT '{}',            -- the connector's own settings, e.g. host, port, TLS, group
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT edge_connection_code_uq UNIQUE (edge_node_id, code)
);

-- What a connection has seen (Sparkplug birth certificates), so tags can be bound by picking them. Upserted by the edge.
CREATE TABLE core.edge_metric (
    connection_id       uuid NOT NULL REFERENCES core.edge_connection(id),
    address             text NOT NULL,                          -- Sparkplug: group/node[/device]:metric
    data_type           text,
    last_value          text,
    last_seen_at        timestamptz NOT NULL,
    PRIMARY KEY (connection_id, address)
);

-- Machine tag mapping (edge binding, D-050). One row per signal the edge reads for a piece of equipment.
CREATE TABLE core.equipment_tag (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    equipment_id        uuid NOT NULL REFERENCES core.equipment(id),
    tag_role            text NOT NULL CHECK (tag_role IN (
                            'state','unit_mode','stop_reason','alarm','warning',
                            'processed_count','defective_count','consumed_count',
                            'machine_speed','process_value','level')),
    connection_id       uuid NOT NULL REFERENCES core.edge_connection(id),
    source_address      text NOT NULL,                          -- Sparkplug: group/node[/device]:metric
    uom_id              uuid REFERENCES core.uom(id),
    scale_factor        numeric(18,9) NOT NULL DEFAULT 1,
    scale_offset        numeric(18,9) NOT NULL DEFAULT 0,
    counter_rollover    bigint,                                 -- counters only: the value it wraps at
    deadband            numeric(18,9),                          -- process values only
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX equipment_tag_equipment_ix ON core.equipment_tag (equipment_id, tag_role);
-- One active tag per role on a piece of equipment (process values, alarms and warnings may have several, #26), and one role per address.
CREATE UNIQUE INDEX equipment_tag_role_uq ON core.equipment_tag (equipment_id, tag_role)
    WHERE is_active AND tag_role NOT IN ('process_value', 'alarm', 'warning');
CREATE UNIQUE INDEX equipment_tag_source_uq ON core.equipment_tag (connection_id, source_address) WHERE is_active;

-- Each machine's state as its signals last left it (D-050): current state, so relational. Written by ingest only.
CREATE TABLE core.equipment_live_state (
    equipment_id        uuid PRIMARY KEY REFERENCES core.equipment(id),
    raw_state           integer,                                -- what the machine sent; packml_state is its meaning
    packml_state        smallint NOT NULL REFERENCES core.packml_state(code),
    unit_mode           smallint NOT NULL DEFAULT 1,
    state_since         timestamptz NOT NULL,
    stop_reason         integer,                                -- the latest first-out stop code
    machine_speed       numeric(18,6),
    signal_at           timestamptz NOT NULL,                   -- the newest signal applied
    edge_node_id        uuid REFERENCES core.edge_node(id),
    open_downtime_id    uuid,                                   -- the stop in progress: (id, started_at) into ts.downtime, no FK
    open_downtime_started_at timestamptz,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT equipment_live_downtime_ck CHECK ((open_downtime_id IS NULL) = (open_downtime_started_at IS NULL))
);

-- The last raw value of each machine counter, so a new reading becomes a count (D-050).
CREATE TABLE core.equipment_counter (
    equipment_id        uuid NOT NULL REFERENCES core.equipment(id),
    count_kind          text NOT NULL CHECK (count_kind IN ('processed','defective','consumed')),
    raw_counter         bigint NOT NULL,
    read_at             timestamptz NOT NULL,
    PRIMARY KEY (equipment_id, count_kind)
);

-- PackML unit modes. Default policy: only Production-mode time is planned time.
CREATE TABLE core.unit_mode (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    site_id             uuid REFERENCES core.equipment(id),     -- null = enterprise default
    mode_number         smallint NOT NULL,                      -- 1 Production, 2 Maintenance, 3 Manual, 4+ user-defined
    name                text NOT NULL,
    is_production_time  boolean NOT NULL,
    CONSTRAINT unit_mode_uq UNIQUE NULLS NOT DISTINCT (site_id, mode_number)
);

-- Site-configurable rollup of raw PackML state into OEE categories (D-005).
-- Raw state is always stored, so changing this recalculates OEE without data loss.
CREATE TABLE core.oee_state_category (
    site_id         uuid NOT NULL REFERENCES core.equipment(id),
    packml_state    smallint NOT NULL REFERENCES core.packml_state(code),
    category        text NOT NULL CHECK (category IN (
                        'producing','waiting_external','held_internal',
                        'stopped_faulted','ready_transitioning','no_signal')),
    PRIMARY KEY (site_id, packml_state)
);

-- =====================================================================
-- 3. MATERIAL, BOM AND CAPABILITY
-- =====================================================================

-- Flat groups of materials (D-033). The code is fixed; a class is switched off, never deleted.
-- An external source of material master data that Pulaski pulls from (D-068): an OData v4 service and the entity set holding its items,
-- with a map from Pulaski's import fields to the service's property names. Rows go through the materials import (D-034, D-053) as a
-- file's do. No secrets here: credentials are in the API's configuration, under MaterialConnections:<code>.
CREATE TABLE core.material_connection (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    code                text NOT NULL UNIQUE,                   -- upper case, fixed once created; names the configuration section
    name                text NOT NULL,
    kind                text NOT NULL DEFAULT 'odata' CHECK (kind IN ('odata')),
    base_url            text NOT NULL,                          -- the service root, https
    entity_set          text NOT NULL,                          -- e.g. Products
    filter              text,                                   -- an OData $filter, as the service takes it
    external_system     text NOT NULL,                          -- what the items are matched on with their key (D-033)
    field_map           jsonb NOT NULL,                         -- {"code": "ProductNumber", "external_key": "ProductID", ...}
    is_active           boolean NOT NULL DEFAULT true,
    last_run_at         timestamptz,
    last_run_by         text,
    last_run_summary    text,                                   -- what the last import (not a check) did, for the screen
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT material_connection_external_ck CHECK (length(external_system) BETWEEN 1 AND 100)
);

CREATE TABLE core.material_class (
    id          uuid PRIMARY KEY DEFAULT uuidv7(),
    code        text NOT NULL UNIQUE,
    name        text NOT NULL,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.material (
    id                  uuid PRIMARY KEY DEFAULT uuidv7(),
    code                text NOT NULL UNIQUE,                   -- item / part number
    name                text NOT NULL,
    description         text CHECK (length(description) <= 2000),
    material_type       text NOT NULL CHECK (material_type IN ('raw','intermediate','finished','packaging','consumable','rework')),
    material_class_id   uuid REFERENCES core.material_class(id),
    base_uom_id         uuid NOT NULL REFERENCES core.uom(id),
    is_lot_tracked      boolean NOT NULL DEFAULT true,
    shelf_life_days     integer CHECK (shelf_life_days > 0),    -- a new lot expires this long after it arrives (D-032)
    batch_size          numeric(18,6) CHECK (batch_size > 0),  -- made in batches of this many base units (D-036); null: continuous
    batch_tolerance_pct numeric(5,2) NOT NULL DEFAULT 2 CHECK (batch_tolerance_pct >= 0 AND batch_tolerance_pct <= 50),  -- 'near' batches may differ by this much
    batch_rule          text CHECK (batch_rule IN ('exact','near')),  -- exact: every batch the batch size, partials approved; near: within the tolerance
    erp_batch_rule      text CHECK (erp_batch_rule IN ('reject','round_up','round_down','hold')),  -- for ERP orders that aren't whole batches (D-066); null: the site's
    origin              text NOT NULL DEFAULT 'local' CHECK (origin IN ('erp','local')),
    external_system     text,
    external_key        text,
    external_version    text,
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT material_erp_ck CHECK (origin = 'local' OR (external_system IS NOT NULL AND external_key IS NOT NULL)),
    CONSTRAINT material_batch_ck CHECK ((batch_size IS NULL) = (batch_rule IS NULL))
);
CREATE UNIQUE INDEX material_external_uq ON core.material (external_system, external_key) WHERE external_key IS NOT NULL;

ALTER TABLE core.residence_time
    ADD CONSTRAINT residence_time_material_fk FOREIGN KEY (material_id) REFERENCES core.material(id);

-- A conversion true for one material only (D-026): 1 from_uom = factor to_uom, e.g.
-- 1 m of a profile = 1.6 kg, or 1 box of end caps = 500 ea. It works both ways and
-- combines with the standard factors (so ft to lb follows from m to kg). A material's
-- conversions never form two routes between the same units. Removing one switches it off.
CREATE TABLE core.material_uom_conversion (
    material_id     uuid NOT NULL REFERENCES core.material(id),
    from_uom_id     uuid NOT NULL REFERENCES core.uom(id),
    to_uom_id       uuid NOT NULL REFERENCES core.uom(id),
    factor          numeric(24,12) NOT NULL CHECK (factor > 0),
    is_active       boolean NOT NULL DEFAULT true,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (material_id, from_uom_id, to_uom_id),
    CONSTRAINT material_uom_conversion_self_ck CHECK (from_uom_id <> to_uom_id)
);

-- Process routes (D-023, ISA-95 operations definition): a reusable template such as
-- "Extrude and Pack". Operations run on one or more lines or departments, each with a
-- share of the quantity; links say whether an operation starts after the one before it
-- starts or ends. Versions: a draft is edited, a released version is fixed and is what
-- orders are made from, releasing a newer one makes it obsolete.
CREATE TABLE core.process (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    site_id         uuid NOT NULL REFERENCES core.equipment(id),
    code            text NOT NULL,
    name            text NOT NULL,
    description     text,
    makes_all_materials boolean NOT NULL DEFAULT false,         -- the scope: every material, or the classes and items below
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT process_code_uq UNIQUE (site_id, code)
);

-- What a process can make, beyond makes_all_materials: whole material classes and single
-- materials. A row taken out of the scope is switched off, not deleted.
CREATE TABLE core.process_material_class (
    process_id          uuid NOT NULL REFERENCES core.process(id),
    material_class_id   uuid NOT NULL REFERENCES core.material_class(id),
    is_active           boolean NOT NULL DEFAULT true,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (process_id, material_class_id)
);

CREATE TABLE core.process_material (
    process_id      uuid NOT NULL REFERENCES core.process(id),
    material_id     uuid NOT NULL REFERENCES core.material(id),
    is_active       boolean NOT NULL DEFAULT true,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (process_id, material_id)
);
CREATE INDEX process_material_material_ix ON core.process_material (material_id) WHERE is_active;

-- The definition (operations, their equipment and the links) is one document, so editing a
-- draft never deletes rows. A released version is also written out below, row by row,
-- because jobs will reference its operations (D-010).
CREATE TABLE core.process_version (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    process_id      uuid NOT NULL REFERENCES core.process(id),
    version_number  integer NOT NULL CHECK (version_number > 0),
    status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','released','obsolete')),
    definition      jsonb NOT NULL DEFAULT '{"operations":[],"dependencies":[]}',
    released_at     timestamptz,
    note            text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT process_version_uq UNIQUE (process_id, version_number),
    CONSTRAINT process_version_released_ck CHECK ((status = 'draft') = (released_at IS NULL))
);
-- At most one draft and one released version per process.
CREATE UNIQUE INDEX process_version_draft_uq ON core.process_version (process_id) WHERE status = 'draft';
CREATE UNIQUE INDEX process_version_released_uq ON core.process_version (process_id) WHERE status = 'released';

-- A released version's operations, fixed from release on.
CREATE TABLE core.process_operation (
    id                  uuid PRIMARY KEY,                       -- the id in the definition
    process_version_id  uuid NOT NULL REFERENCES core.process_version(id),
    operation_number    integer NOT NULL CHECK (operation_number > 0),
    name                text NOT NULL,
    description         text,
    CONSTRAINT process_operation_uq UNIQUE (process_version_id, operation_number)
);

CREATE TABLE core.process_operation_equipment (
    operation_id    uuid NOT NULL REFERENCES core.process_operation(id),
    equipment_id    uuid NOT NULL REFERENCES core.equipment(id),
    share_percent   numeric(5,2) NOT NULL CHECK (share_percent > 0 AND share_percent <= 100),
    PRIMARY KEY (operation_id, equipment_id)
);

CREATE TABLE core.process_dependency (
    id                  uuid PRIMARY KEY,                       -- the id in the definition
    from_operation_id   uuid NOT NULL REFERENCES core.process_operation(id),
    to_operation_id     uuid NOT NULL REFERENCES core.process_operation(id),
    dependency_type     text NOT NULL CHECK (dependency_type IN ('after_start','after_end')),
    lag                 interval NOT NULL DEFAULT interval '0' CHECK (lag >= interval '0'),
    CONSTRAINT process_dependency_self_ck CHECK (from_operation_id <> to_operation_id),
    CONSTRAINT process_dependency_uq UNIQUE (from_operation_id, to_operation_id)
);

-- The process order creation pre-selects for a material, among those whose scope covers it;
-- the planner may pick another.
ALTER TABLE core.material
    ADD COLUMN default_process_id uuid REFERENCES core.process(id);

-- Bills of materials (D-025): what one material is made from, one level deep. A BOM
-- belongs to a material and may name a process (one BOM per material and process, and
-- one with none); its items then name the operation that consumes them. Versioned like
-- processes: a draft's items are one document, a released version is written out as
-- fixed rows that planned components reference.
CREATE TABLE core.bom (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    material_id     uuid NOT NULL REFERENCES core.material(id),   -- the output
    process_id      uuid REFERENCES core.process(id),             -- null: any process
    is_active       boolean NOT NULL DEFAULT true,
    origin          text NOT NULL DEFAULT 'local' CHECK (origin IN ('erp','local')),
    external_system text,
    external_key    text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT bom_uq UNIQUE NULLS NOT DISTINCT (material_id, process_id),
    CONSTRAINT bom_erp_ck CHECK (origin = 'local' OR (external_system IS NOT NULL AND external_key IS NOT NULL))
);

CREATE TABLE core.bom_version (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    bom_id          uuid NOT NULL REFERENCES core.bom(id),
    version_number  integer NOT NULL CHECK (version_number > 0),
    status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','released','obsolete')),
    base_qty        core.qty NOT NULL CHECK (base_qty > 0),        -- items are per this much output
    base_uom_id     uuid NOT NULL REFERENCES core.uom(id),
    definition      jsonb NOT NULL DEFAULT '{"items":[]}',
    released_at     timestamptz,
    note            text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT bom_version_uq UNIQUE (bom_id, version_number),
    CONSTRAINT bom_version_released_ck CHECK ((status = 'draft') = (released_at IS NULL))
);
-- At most one draft and one released version per BOM.
