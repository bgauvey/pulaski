-- Creates monthly partitions (UTC bounds). A worker calls this ahead of
-- time; pg_partman can replace it. Telemetry may use daily instead.
CREATE FUNCTION ts.create_month_partitions(p_parent regclass, p_from date, p_months integer)
RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    v_schema text;
    v_table  text;
    v_start  date;
    v_end    date;
BEGIN
    SELECT n.nspname, c.relname INTO v_schema, v_table
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.oid = p_parent;

    FOR i IN 0 .. p_months - 1 LOOP
        v_start := (date_trunc('month', p_from) + make_interval(months => i))::date;
        v_end   := (v_start + interval '1 month')::date;
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I.%I PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
            v_schema, v_table || '_p' || to_char(v_start, 'YYYYMM'), p_parent,
            (v_start::timestamp AT TIME ZONE 'UTC'), (v_end::timestamp AT TIME ZONE 'UTC'));
    END LOOP;
END $$;

-- Keeps every partitioned history table ready ahead of time (D-028).
-- Creates the current month and the next p_months - 1 for every range-partitioned table in ts
-- and evt, and returns how many partitions it created (0 when all were there). SECURITY
-- DEFINER: it runs as the schema owner, because creating a partition needs ownership of its
-- parent, which pulaski_app doesn't have. db/app-role.sql grants EXECUTE to pulaski_app only.
CREATE FUNCTION ts.ensure_partitions(p_months integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_parent regclass;
    v_before integer;
    v_after  integer;
BEGIN
    IF p_months IS NULL OR p_months < 1 OR p_months > 24 THEN
        RAISE EXCEPTION 'ensure_partitions: months must be between 1 and 24, not %', p_months;
    END IF;

    SELECT count(*) INTO v_before FROM pg_class WHERE relispartition AND relkind = 'r';
    FOR v_parent IN
        SELECT pt.partrelid::regclass
        FROM pg_partitioned_table pt
        JOIN pg_class c ON c.oid = pt.partrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname IN ('ts', 'evt') AND pt.partstrat = 'r'
        ORDER BY 1
    LOOP
        PERFORM ts.create_month_partitions(v_parent, current_date, p_months);
    END LOOP;
    SELECT count(*) INTO v_after FROM pg_class WHERE relispartition AND relkind = 'r';
    RETURN v_after - v_before;
END $$;

REVOKE ALL ON FUNCTION ts.ensure_partitions(integer) FROM PUBLIC;

-- Drops the monthly ts.process_value partitions that end more than p_keep_days ago; returns how many. SECURITY DEFINER, like
-- ts.ensure_partitions: dropping a partition needs ownership, which pulaski_app doesn't have. Only this table, never less than a week.
CREATE FUNCTION ts.drop_old_process_values(p_keep_days integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_part   regclass;
    v_bound  text;
    v_end    timestamptz;
    v_dropped integer := 0;
BEGIN
    IF p_keep_days IS NULL OR p_keep_days < 7 THEN
        RAISE EXCEPTION 'drop_old_process_values: keep at least 7 days, not %', p_keep_days;
    END IF;

    FOR v_part, v_bound IN
        SELECT c.oid::regclass, pg_get_expr(c.relpartbound, c.oid)
        FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
        WHERE i.inhparent = 'ts.process_value'::regclass
    LOOP
        -- FOR VALUES FROM ('…') TO ('…'): the upper bound is the second quoted value.
        v_end := (regexp_match(v_bound, 'TO \(''([^'']+)''\)'))[1]::timestamptz;
        IF v_end IS NOT NULL AND v_end <= now() - make_interval(days => p_keep_days) THEN
            EXECUTE format('DROP TABLE %s', v_part);
            v_dropped := v_dropped + 1;
        END IF;
    END LOOP;
    RETURN v_dropped;
END $$;

REVOKE ALL ON FUNCTION ts.drop_old_process_values(integer) FROM PUBLIC;

